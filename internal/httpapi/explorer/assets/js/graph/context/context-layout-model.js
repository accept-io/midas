// /explorer/assets/js/graph/context/context-layout-model.js
//
// D37o-impl-1 — Context Layout Model.
//
// Pure-data, renderer-independent builder that takes ContextCard[] and
// ContextConnector[] (produced by the card and connector models) and
// emits a `LayoutSpec` — band assignments, ordering, overflow sentinel,
// directionality rules, density hints, fit hints. No pixel coordinates
// are part of the contract; the renderer downstream composes
// coordinates from the spec plus host viewport / safe-area output.
//
// Output contract: see D37o-design-1 §6 (LayoutSpec shape).
//
// Public surface (attached to MIDASExplorerGraph.contextModels.layout):
//   BAND_IDS         — frozen list of the five band ids
//   LAYER_ORDER      — frozen top→bottom ordering
//   GOVERNANCE_SLOTS — frozen { top: kind, bottom: kind } column shape
//   DEFAULTS         — frozen default density / overflow constants
//   buildLayout      — (cards, connectors, options) → LayoutSpec
//   assignBandForCard — (card) → band id (or 'governance' / null)
//
// Working decision D-LAY-1 (D37o-design-1 §6.7): ai_system_binding
// nodes are emitted as edges only in MVP; the layout model omits any
// ai_system_binding cards from the band assignment. If a future
// tranche elects to render bindings as cards, the assignment rule can
// be added additively.
//
// Constraints (D37o-design-1 §6.1):
//   - No DOM measurements.
//   - No graph-engine positions.
//   - No host viewport reads (safe-area is consumed by the renderer,
//     not by the model; the model emits an intent flag only).
//   - No pixel coordinates as part of the contract.

(function () {
  'use strict';

  if (typeof window === 'undefined') return;
  window.MIDASExplorerGraph              = window.MIDASExplorerGraph || {};
  window.MIDASExplorerGraph.contextModels = window.MIDASExplorerGraph.contextModels || {};

  // ── Constants ──────────────────────────────────────────────────────

  var BAND_IDS = Object.freeze([
    'related',
    'root',
    'cap-proc',
    'surface',
    'ai',
  ]);

  // Strict top→bottom layer ordering.
  var LAYER_ORDER = Object.freeze(['related', 'root', 'cap-proc', 'surface', 'ai']);

  // Governance column slot assignments. Top slot parallels the root
  // band; bottom slot parallels the surface band.
  var GOVERNANCE_SLOTS = Object.freeze({
    top:    'authority_summary',
    bottom: 'coverage',
  });

  // Density / overflow defaults. Mirror the legacy
  // `GMAP.MAX_PER_LAYER` value used by the current Context renderer.
  // Renderers may override via `options.maxCardsPerBand` if needed.
  var DEFAULTS = Object.freeze({
    maxCardsPerBand:  6,
    cardMinSpacingPx: 12,
    centreOnRoot:    true,
    paddingMode:    'safe-area-aware',
  });

  // Overflow sentinel kind is intentionally an internal token, not a
  // Context node kind. Renderers must treat it as a renderer-only
  // construct generated by the layout model.
  var SENTINEL_KIND = '_overflow_sentinel';

  // Directionality rules — derived from the connector model semantics,
  // surfaced here so the renderer can answer "which edges flow top
  // down" without re-deriving from edge-kind taxonomy.
  var DIRECTIONALITY_RULES = Object.freeze({
    topDown:          Object.freeze(['has_capability', 'has_process', 'has_surface']),
    bidirectional:    Object.freeze(['relates_to']),
    governanceInward: Object.freeze(['summarises', 'reports_coverage']),
    freeform:         Object.freeze(['bound_to', 'system_of']),
  });

  // ── Helpers ────────────────────────────────────────────────────────

  function _isPlainObject(v) {
    return v != null && typeof v === 'object' && !Array.isArray(v);
  }

  function _str(v) {
    if (v == null) return '';
    return String(v);
  }

  function _newBand(id) {
    return { id: id, cards: [], maxCardsPerBand: DEFAULTS.maxCardsPerBand };
  }

  function _newSlot(cardId, order, emphasis) {
    return { cardId: _str(cardId), order: order | 0, emphasis: emphasis || 'normal' };
  }

  function _newSentinel(layerLabel, total, rendered) {
    return {
      kind:       SENTINEL_KIND,
      layerLabel: _str(layerLabel),
      total:      total | 0,
      rendered:   rendered | 0,
    };
  }

  function _layerLabelForBand(bandId) {
    switch (bandId) {
      case 'related':  return 'Related Business Services';
      case 'root':     return 'Root';
      case 'cap-proc': return 'Capabilities & Processes';
      case 'surface':  return 'Decision Surfaces';
      case 'ai':       return 'AI Systems';
      default:         return _str(bandId);
    }
  }

  // ── Band assignment ────────────────────────────────────────────────

  // assignBandForCard — return one of: 'related' | 'root' | 'cap-proc'
  // | 'surface' | 'ai' | 'governance' | null. `null` indicates the
  // card is intentionally omitted from the layout (e.g. ai_system_binding
  // per D-LAY-1).
  function assignBandForCard(card) {
    if (!_isPlainObject(card)) return null;
    var role = _str(card.role);
    var kind = _str(card.kind);
    if (role === 'root')       return 'root';
    if (role === 'governance') return 'governance';
    switch (kind) {
      case 'related_business_service': return 'related';
      case 'capability':               return 'cap-proc';
      case 'process':                  return 'cap-proc';
      case 'decision_surface':         return 'surface';
      case 'ai_system':                return 'ai';
      case 'ai_system_binding':        return null; // D-LAY-1: edges only in MVP
      default:                         return null;
    }
  }

  function _isLeftColumnKind(kind) {
    return _str(kind) === 'capability';
  }

  function _isRightColumnKind(kind) {
    return _str(kind) === 'process';
  }

  // ── Layout build ───────────────────────────────────────────────────

  function buildLayout(cards, connectors, options) {
    var maxPerBand = (options && typeof options.maxCardsPerBand === 'number')
      ? options.maxCardsPerBand
      : DEFAULTS.maxCardsPerBand;

    var spec = {
      // D37p-impl-2 — surface the shared `layoutKind` token the
      // platform stage composer (graph-stage.js) keys on. Stable
      // generic field; not a renderer concern.
      layoutKind:       'banded',
      bands: [],
      governanceColumn: { id: 'governance', cards: [] },
      overflowPolicy: {
        policy:        'cap-with-sentinel',
        sentinelKind:  SENTINEL_KIND,
        sentinelCards: [], // per-band sentinels populated below
      },
      layerOrder:     LAYER_ORDER.slice(),
      directionality: {
        topDown:          DIRECTIONALITY_RULES.topDown.slice(),
        bidirectional:    DIRECTIONALITY_RULES.bidirectional.slice(),
        governanceInward: DIRECTIONALITY_RULES.governanceInward.slice(),
        freeform:         DIRECTIONALITY_RULES.freeform.slice(),
      },
      density: {
        maxCardsPerBandDefault: maxPerBand,
        cardMinSpacingPx:       DEFAULTS.cardMinSpacingPx,
      },
      fit: {
        centreOnRoot: DEFAULTS.centreOnRoot,
        paddingMode:  DEFAULTS.paddingMode,
      },
    };

    // Initialise empty bands in strict order.
    var bandIndex = {};
    for (var i = 0; i < LAYER_ORDER.length; i++) {
      var band = _newBand(LAYER_ORDER[i]);
      band.maxCardsPerBand = maxPerBand;
      spec.bands.push(band);
      bandIndex[LAYER_ORDER[i]] = band;
    }

    // Cap-proc split columns initialised lazily.
    var capProcBand = bandIndex['cap-proc'];
    capProcBand.splitColumns = { left: [], right: [] };

    var safeCards = Array.isArray(cards) ? cards : [];

    // Per-band running orders.
    var orders = { related: 0, root: 0, surface: 0, ai: 0, capLeft: 0, capRight: 0, govTop: 0, govBottom: 0 };

    // First pass: assign to bands or governance column.
    for (var j = 0; j < safeCards.length; j++) {
      var card = safeCards[j];
      var dest = assignBandForCard(card);
      if (dest === null) continue;
      if (dest === 'governance') {
        var govSlot;
        if (_str(card.kind) === GOVERNANCE_SLOTS.top) {
          govSlot = _newSlot(card.id, orders.govTop++, 'normal');
          govSlot.governancePosition = 'top';
        } else if (_str(card.kind) === GOVERNANCE_SLOTS.bottom) {
          govSlot = _newSlot(card.id, orders.govBottom++, 'normal');
          govSlot.governancePosition = 'bottom';
        } else {
          govSlot = _newSlot(card.id, spec.governanceColumn.cards.length, 'normal');
          govSlot.governancePosition = 'other';
        }
        spec.governanceColumn.cards.push(govSlot);
        continue;
      }
      var targetBand = bandIndex[dest];
      if (!targetBand) continue;

      if (dest === 'cap-proc') {
        var slot;
        if (_isLeftColumnKind(card.kind)) {
          slot = _newSlot(card.id, orders.capLeft++, 'normal');
          targetBand.splitColumns.left.push(slot);
        } else if (_isRightColumnKind(card.kind)) {
          slot = _newSlot(card.id, orders.capRight++, 'normal');
          targetBand.splitColumns.right.push(slot);
        } else {
          slot = _newSlot(card.id, targetBand.cards.length, 'normal');
        }
        targetBand.cards.push(slot);
        continue;
      }

      var emphasis = dest === 'root' ? 'root' : 'normal';
      var orderKey = dest === 'related' ? 'related'
                  : dest === 'root'    ? 'root'
                  : dest === 'surface' ? 'surface'
                  : dest === 'ai'      ? 'ai'
                  : null;
      var ord = orderKey ? orders[orderKey]++ : targetBand.cards.length;
      targetBand.cards.push(_newSlot(card.id, ord, emphasis));
    }

    // Second pass: overflow sentinel per band. Sentinels are emitted
    // into the layout spec under the overflow-rule sentinelCards
    // array, not into the card model output; this keeps the card
    // vocabulary clean.
    for (var k = 0; k < spec.bands.length; k++) {
      var b = spec.bands[k];
      _applyOverflow(b, spec.overflowPolicy, maxPerBand);
    }

    // Connector summary — the layout model surfaces the count and kind
    // mix so the renderer can derive z-ordering hints without a second
    // pass over the connector list. Connector specs themselves remain
    // owned by the connector model.
    spec.connectorSummary = _summariseConnectors(connectors);

    return spec;
  }

  function _applyOverflow(band, rule, maxPerBand) {
    if (!band || !Array.isArray(band.cards)) return;
    if (band.id === 'root') return; // root band never overflows; one card by definition

    // Split-column bands apply overflow per column.
    if (band.splitColumns) {
      _applyOverflowToColumn(band.splitColumns.left,  band, 'left',  rule, maxPerBand);
      _applyOverflowToColumn(band.splitColumns.right, band, 'right', rule, maxPerBand);
      return;
    }

    if (band.cards.length <= maxPerBand) return;
    var keep = maxPerBand - 1;
    if (keep < 0) keep = 0;
    var truncated = band.cards.slice(0, keep);
    var total     = band.cards.length;
    band.cards = truncated;
    rule.sentinelCards.push(Object.assign(
      _newSentinel(_layerLabelForBand(band.id), total, truncated.length),
      { bandId: band.id }
    ));
  }

  function _applyOverflowToColumn(column, band, columnId, rule, maxPerBand) {
    if (!Array.isArray(column)) return;
    if (column.length <= maxPerBand) return;
    var keep = maxPerBand - 1;
    if (keep < 0) keep = 0;
    var total     = column.length;
    var truncated = column.slice(0, keep);
    // Mutate the column array in place to preserve the band reference.
    column.length = 0;
    for (var i = 0; i < truncated.length; i++) column.push(truncated[i]);
    rule.sentinelCards.push(Object.assign(
      _newSentinel(_layerLabelForBand(band.id) + ' (' + columnId + ')', total, truncated.length),
      { bandId: band.id, column: columnId }
    ));
  }

  function _summariseConnectors(connectors) {
    var out = { total: 0, byVisualClass: {} };
    if (!Array.isArray(connectors)) return out;
    for (var i = 0; i < connectors.length; i++) {
      var c = connectors[i];
      if (!_isPlainObject(c)) continue;
      out.total++;
      var v = _str(c.visualClass);
      if (!v) continue;
      out.byVisualClass[v] = (out.byVisualClass[v] || 0) + 1;
    }
    return out;
  }

  window.MIDASExplorerGraph.contextModels.layout = {
    BAND_IDS:             BAND_IDS,
    LAYER_ORDER:          LAYER_ORDER,
    GOVERNANCE_SLOTS:     GOVERNANCE_SLOTS,
    DEFAULTS:             DEFAULTS,
    SENTINEL_KIND:        SENTINEL_KIND,
    DIRECTIONALITY_RULES: DIRECTIONALITY_RULES,
    buildLayout:          buildLayout,
    assignBandForCard:    assignBandForCard,
  };
})();
